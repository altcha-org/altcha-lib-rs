/// `CounterMode::String` interoperates with the JS reference. Vector generated by
/// altcha-lib `createChallenge`/`solveChallenge` with `counterMode: 'string'`,
/// SHA-256, cost 10, deterministic counter 42, secret `test-secret`.
#[test]
fn string_counter_mode_matches_js_reference() {
    let challenge: Challenge = serde_json::from_str(
        r#"{"parameters":{"algorithm":"SHA-256","cost":10,"keyLength":32,"keyPrefix":"3cf4a48a065fa0fa96d3a80630e73733","nonce":"647e028a083e3d738d7de0ed42793083","salt":"c6c46275373795af264b50063419ef11"},"signature":"257709e6715640be1d1568a3c1b68e99f5ea19aa320f9b1d7dfaea893a915f66"}"#,
    )
    .expect("invalid challenge JSON");
    let js_derived_key = "3cf4a48a065fa0fa96d3a80630e73733599ed4d57580fa9084baa52ef8694ea9";

    let solution = solve_challenge(SolveChallengeOptions {
        counter_mode: CounterMode::String,
        ..SolveChallengeOptions::new(&challenge)
    })
    .expect("solve_challenge failed")
    .expect("no solution found");
    assert_eq!(solution.counter, 42);
    assert_eq!(solution.derived_key, js_derived_key);

    let result = verify_solution(VerifySolutionOptions {
        counter_mode: CounterMode::String,
        ..VerifySolutionOptions::new(&challenge, &solution, secret())
    })
    .expect("verify_solution failed");
    assert!(result.verified, "{result:?}");

    // The same solution re-derived with the uint32 encoding does not match.
    let result = verify_solution(VerifySolutionOptions::new(&challenge, &solution, secret()))
        .expect("verify_solution failed");
    assert_eq!(result.invalid_solution, Some(true));

    // Rust-created string-mode challenges roundtrip as well.
    let challenge = create_challenge(CreateChallengeOptions {
        algorithm: "SHA-256".to_string(),
        cost: 10,
        counter: Some(42),
        counter_mode: CounterMode::String,
        hmac_signature_secret: Some(secret()),
        ..Default::default()
    })
    .expect("create_challenge failed");
    let solution = solve_challenge(SolveChallengeOptions {
        counter_mode: CounterMode::String,
        ..SolveChallengeOptions::new(&challenge)
    })
    .expect("solve_challenge failed")
    .expect("no solution found");
    assert_eq!(solution.counter, 42);
}

