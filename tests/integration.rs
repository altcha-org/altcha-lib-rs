/// Regression test: `key_prefix_length` is capped at half the derived key length. An
/// oversized value used to panic slicing the key; a SHA-256 `key_length` above the 32-byte
/// digest is capped by the actual key, not the requested length.
#[test]
fn key_prefix_length_capped_at_half_key() {
    for (key_length, expected_prefix_bytes) in [(32, 16), (100, 16)] {
        let challenge = create_challenge(CreateChallengeOptions {
            algorithm: "SHA-256".to_string(),
            cost: 10,
            counter: Some(1),
            key_length,
            key_prefix_length: Some(64),
            hmac_signature_secret: Some(secret()),
            ..Default::default()
        })
        .expect("create_challenge failed");

        assert_eq!(
            challenge.parameters.key_prefix.len(),
            expected_prefix_bytes * 2,
            "key_length {key_length}"
        );

        let solution = solve_challenge(SolveChallengeOptions::new(&challenge))
            .expect("solve_challenge failed")
            .expect("no solution found");
        let result = verify_solution(VerifySolutionOptions::new(&challenge, &solution, secret()))
            .expect("verify_solution failed");
        assert!(result.verified, "key_length {key_length}: {result:?}");
    }
}

/// A non-hex `key_prefix` is a server misconfiguration and is rejected when the challenge
/// is created, rather than surfacing as an `Err` from the client's solve.
#[test]
fn create_challenge_rejects_non_hex_key_prefix() {
    for key_prefix in ["zz", "z", "0g"] {
        let result = create_challenge(CreateChallengeOptions {
            algorithm: "SHA-256".to_string(),
            cost: 10,
            key_prefix: key_prefix.to_string(),
            ..Default::default()
        });
        assert!(
            matches!(result, Err(altcha::Error::InvalidParameters(_))),
            "{key_prefix:?}: {result:?}"
        );
    }

    // Deterministic mode replaces key_prefix with the derived prefix, so it is not checked.
    create_challenge(CreateChallengeOptions {
        algorithm: "SHA-256".to_string(),
        cost: 10,
        counter: Some(1),
        key_prefix: "zz".to_string(),
        ..Default::default()
    })
    .expect("deterministic mode ignores key_prefix");
}

/// A non-hex `key_prefix` in a signed challenge from elsewhere is invalid input regardless
/// of its length: solve and verify both return `InvalidParameters`. Previously an
/// even-length prefix failed hex decoding while an odd-length one made solve run until
/// the timeout and verify report `invalid_solution`.
#[test]
fn solve_and_verify_reject_non_hex_key_prefix() {
    for key_prefix in ["zz", "zzz"] {
        let mut params = create_challenge(CreateChallengeOptions {
            algorithm: "SHA-256".to_string(),
            cost: 10,
            ..Default::default()
        })
        .expect("create_challenge failed")
        .parameters;
        params.key_prefix = key_prefix.to_string();
        let challenge = sign_challenge(&HmacAlgorithm::Sha256, &mut params, None, &secret(), None)
            .expect("sign_challenge failed");

        let solved = solve_challenge(SolveChallengeOptions {
            timeout_ms: 100,
            ..SolveChallengeOptions::new(&challenge)
        });
        assert!(
            matches!(solved, Err(altcha::Error::InvalidParameters(_))),
            "solve {key_prefix:?}: {solved:?}"
        );

        let solution = Solution {
            counter: 0,
            derived_key: "00".repeat(32),
            time: None,
        };
        let verified = verify_solution(VerifySolutionOptions::new(&challenge, &solution, secret()));
        assert!(
            matches!(verified, Err(altcha::Error::InvalidParameters(_))),
            "verify {key_prefix:?}: {verified:?}"
        );
    }
}

